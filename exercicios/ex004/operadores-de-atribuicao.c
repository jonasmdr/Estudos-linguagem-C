#include <stdio.h>

int main(){
    /*
    Atribuiçao simples (=)
    Atribuiçao com soma (+=)
    Atribuiçao com subtraçao (-=)
    Atribuiçao com multiplicaçao (*=)
    Atribuiçao com divisao (/=)

    Os atalhos (como o +=, -=, *= ou /=) só são usados quando você quer atualizar o valor de uma variável usando ela mesma.

    */
   int num1, num2, resul;
    num1 = 5;
    num2 = 7;
    resul = num1 + num2;
    resul += 20;

   printf("%d", resul);




}